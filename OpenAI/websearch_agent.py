"""
Web Search Agent – Searches the internet for relevant Indian legal cases
and precedents when the local Qdrant vector database doesn't have
sufficient data. Uses Groq (lightweight, fast) for query reformulation
and result summarization.

Responsibilities:
1. Accept search queries from the Orchestrator (generated by the Judge).
2. Execute DuckDuckGo web searches for Indian legal cases.
3. Summarize and structure the search results using Groq.
"""

import os
import sys
from pathlib import Path

root_dir = str(Path(__file__).resolve().parent.parent)
if root_dir not in sys.path:
    sys.path.insert(0, root_dir)

from dotenv import load_dotenv
env_local = Path(__file__).resolve().parent / ".env"
env_rag = Path(__file__).resolve().parent.parent / "RAG" / ".env"
if env_local.exists():
    load_dotenv(dotenv_path=env_local)
elif env_rag.exists():
    load_dotenv(dotenv_path=env_rag)
else:
    load_dotenv()

from langchain_groq import ChatGroq
from langchain_community.tools import DuckDuckGoSearchResults
from typing import List, Optional


class WebSearchAgent:
    """Uses Groq (lightweight) for query refinement and result summarization,
    and DuckDuckGo for actual web searches."""

    def __init__(self):
        self.llm = ChatGroq(
            model=os.getenv("GROQ_MODEL", "openai/gpt-oss-120b"),
            temperature=0,
            groq_api_key=os.getenv("GROQ_API_KEY")
        )
        self.search_tool = DuckDuckGoSearchResults(
            max_results=5,
            output_format="list"
        )

    def refine_search_queries(self, raw_queries: List[str], user_query: str) -> List[str]:
        """Uses Groq to refine search queries for better legal results."""
        prompt = f"""
You are a legal research assistant. Refine the following search queries to find
relevant Indian Supreme Court cases, High Court decisions, or statutory provisions.
Make each query specific and targeted for Indian legal databases.

Original user question: "{user_query}"
Raw search suggestions: {raw_queries}

Return exactly 2-3 refined search queries, one per line.
Only output the queries, nothing else.
"""
        try:
            response = self.llm.invoke(prompt)
            content = response.content if hasattr(response, "content") else str(response)
            refined = [q.strip().strip('"').strip("'").lstrip("0123456789.-) ") for q in content.strip().split("\n") if q.strip()]
            return refined[:3] if refined else raw_queries[:3]
        except Exception:
            return raw_queries[:3]

    def search(self, queries: List[str]) -> List[dict]:
        """Executes web searches and returns structured results."""
        all_results = []
        seen_links = set()

        for query in queries:
            try:
                raw_results = self.search_tool.invoke(query)
                if isinstance(raw_results, list):
                    for item in raw_results:
                        link = item.get("link", "")
                        if link not in seen_links:
                            seen_links.add(link)
                            all_results.append({
                                "title": item.get("title", ""),
                                "snippet": item.get("snippet", ""),
                                "link": link,
                                "query_used": query
                            })
                elif isinstance(raw_results, str):
                    all_results.append({
                        "title": f"Search results for: {query}",
                        "snippet": raw_results[:500],
                        "link": "",
                        "query_used": query
                    })
            except Exception as e:
                all_results.append({
                    "title": f"Search failed for: {query}",
                    "snippet": str(e),
                    "link": "",
                    "query_used": query
                })

        return all_results

    def summarize_results(self, user_query: str, search_results: List[dict]) -> str:
        """Uses Groq (lightweight) to summarize web search results into legal context."""
        if not search_results:
            return ""

        results_text = "\n\n".join([
            f"Source: {r.get('title', 'Unknown')}\nURL: {r.get('link', 'N/A')}\nExcerpt: {r.get('snippet', '')}"
            for r in search_results
        ])

        prompt = f"""
You are a legal research summarizer. The user asked: "{user_query}"

The following web search results were found. Extract ONLY legally relevant
information: case names, case citations, statutory provisions, court holdings,
and legal principles. Ignore irrelevant results.

Search Results:
{results_text}

Produce a concise legal summary (max 400 words). Include case citations and
statute references where found. If no legally relevant results, say "No relevant
legal cases found from web search."
"""
        try:
            response = self.llm.invoke(prompt)
            return response.content if hasattr(response, "content") else str(response)
        except Exception as e:
            return f"Web search summarization failed: {str(e)}"

    def execute_full_search(self, search_queries: List[str], user_query: str) -> dict:
        """Complete pipeline: refine queries -> search -> summarize."""
        refined_queries = self.refine_search_queries(search_queries, user_query)
        raw_results = self.search(refined_queries)
        summary = self.summarize_results(user_query, raw_results)

        return {
            "refined_queries": refined_queries,
            "raw_results": raw_results,
            "summary": summary
        }
